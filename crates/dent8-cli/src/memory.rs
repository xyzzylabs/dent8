//! `dent8 export --target <FILE>` and `dent8 import <FILE>`: the native-memory **write path**
//! between the dent8 fact store and provider-native memory files (`CLAUDE.md`, `AGENTS.md`,
//! `GEMINI.md`, `.cursor/rules`, …).
//!
//! Both halves go *through* the existing firewall, never around it:
//!
//! - **Export** renders the currently-believed facts (the same belief/freshness/contested
//!   selection `dent8 context` uses) into a delimited **managed block** and splices it
//!   idempotently into the target file. It writes the file from the CLI process itself — the
//!   sanctioned channel the `Write`/`Edit`-scoped `PreToolUse` guard does not intercept — and
//!   every rendered line carries a `dent8://<kind>/<key>/<predicate>` receipt marker plus the
//!   believed event's id and hash, so `native scan`/`reconcile` (and the guard's
//!   `post-write-audit` mode) recognize the block as dent8-managed rather than unmanaged drift.
//! - **Import** parses durable facts out of a memory file with deterministic, documented rules
//!   (no LLM, no fabrication) and routes **every** recovered proposal through the exact same
//!   `capture::apply_proposal` funnel the `capture` command uses — so an imported fact cannot
//!   smuggle itself past authority, policy, or the content check.
//!
//! ## Managed-block format
//!
//! ```text
//! <!-- BEGIN dent8 managed block (generated by `dent8 export`; edits inside are overwritten) -->
//! <!-- dent8 export: 2 believed fact(s); do not edit inside this block — run `dent8 export --target <file>` to refresh -->
//!
//! ### repo:dent8
//! - `dent8://repo/dent8/test_command` = "cargo test"  <!-- dent8 receipt fact=fact:repo:dent8:test_command:1 event_hash=abcd… authority=medium source=source:human -->
//! <!-- END dent8 managed block -->
//! ```
//!
//! Each fact line puts the authoritative data in the `dent8://kind/key/predicate` marker plus
//! the rendered value; import recovers subject/predicate/value from exactly those, which is what
//! makes the round-trip stable.
//!
//! ## Import rules
//!
//! 1. **Managed block** (inverse of export): each fact line inside a `dent8` managed block →
//!    an `assert` proposal recovered from the marker + rendered value.
//! 2. **Inline receipt markers in prose**: a line anywhere carrying a `dent8://kind/key/predicate`
//!    marker followed by `= <value>` → an `assert` proposal (lets a human hand-annotate facts).
//! 3. **Fenced `dent8` code block**: a fenced block tagged ```` ```dent8 ```` whose lines are JSON
//!    `Proposal`s (the same format `capture` reads) → proposals, applied verbatim.
//!
//! Everything else (free prose, headings, arbitrary bullets, other code fences) is **skipped**
//! and reported — import never invents a fact.

